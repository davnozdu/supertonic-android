package com.brahmadeo.supertonic.tts.llm

import com.brahmadeo.supertonic.tts.utils.*
import java.io.File

fun vis(s: String?) = s?.map { c -> when { c == '­' -> "{SHY}"; c == '̈' -> "{U+0308}"; c == '﻿' -> "{BOM}"; c == '‍' -> "{ZWJ}"; c == '⁠' -> "{WJ}"; c == ' ' -> "{NBSP}"; c.code in 0x00C0..0x024F -> "{Lat:$c}"; c == '̀' -> "{GRAVE}"; else -> c.toString() } }?.joinToString("") ?: "null(REJECT)"

fun main(args: Array<String>) {
    RussianNames.initForTests(File(args[0]).useLines { RussianNames.load(it) })
    fun v(id: String, src: String, llm: String) {
        var reason = "-"
        val ok = PreparedTextValidator.validate(src, llm) { reason = it }
        val rep = if (ok == null) PreparedTextRepair.repair(src, llm)?.let { PreparedTextValidator.validate(src, it.text) } else null
        println("$id: валидатор=${vis(ok)} причина=$reason | после ремонта=${if (ok != null) "не нужен" else vis(rep)}")
    }
    v("Q01 прямые → ёлочки", "Он сказал: \"Иди домой\".", "Он сказа́л: «Иди́ домо́й».")
    v("Q02 ёлочки → прямые", "Он сказал: «Иди домой».", "Он сказа́л: \"Иди́ домо́й\".")
    v("Q03 вложенные „“ → «»", "«Он сказал: „Иди домой“», — ответила она.", "«Он сказа́л: «Иди́ домо́й»», — отве́тила она́.")
    v("Q04 точка внутрь кавычек", "Он сказал: «Иди домой».", "Он сказа́л: «Иди́ домо́й.»")
    v("Q05 апостроф ’ → '", "Пришёл д’Артаньян.", "Пришёл д'Артанья́н.")
    v("Q06 апостроф ’ сохранён", "Пришёл д’Артаньян.", "Пришёл д’Артанья́н.")
    v("Q07 мягкий перенос пропал", "Он пил мо­локо.", "Он пил молоко́.")
    v("Q08 мягкий перенос сохранён", "Он пил мо­локо.", "Он пил мо­локо́.")
    v("Q09 BOM в начале пропал", "﻿Он пил молоко.", "Он пил молоко́.")
    v("Q10 е+U+0308 → ё", "Пришёл ёж колючий.".replace("Пришёл ", "Пришёл "), "Пришёл ёж колю́чий.")
    v("Q11 латинская á как ударение", "Он пил молокó.", "Он пил молоко́.")
    v("Q12 сноска ¹ → 1", "Он пил молоко¹.", "Он пил молоко́1.")
    v("Q13 сноска ¹ сохранена", "Он пил молоко¹.", "Он пил молоко́¹.")
    v("Q14 добавлены кавычки в реплику без кавычек", "— Иди домой, — сказал он.", "— «Иди́ домо́й», — сказа́л он.")
    v("Q15 тире-дефис между словами", "Он — врач.", "Он - врач.")
    v("Q16 ‹› одиночные ёлочки", "Слово ‹дом› старое.", "Сло́во \"дом\" ста́рое.")
    v("Q17 многоточие", "Он ушёл...", "Он ушёл…")
    v("Q18 знак ударения grave", "Он пил молоко̀.", "Он пил молоко́.")
    println("--- нормализатор книги (вход LLM)")
    for (t in listOf("Он пил мо­локо.", "﻿Он пришёл.", "Пришёл ёж.", "Он пил молокó.", "Он пил молоко¹.", "Текст[12] дальше.", "д’Артаньян и О'Генри", "«Да».«Нет»", "Слово‹дом›", "100 км"))
        println("${vis(t)} → ${vis(RussianBookNormalizer.normalize(t, expandNumbers = false, dates = false))}")
    println("--- словарь имён / Семена")
    RussianNames.forget()
    for (t in listOf("Пришла Федо́ра Егоровна.", "Пришла Федора Егоровна.", "Он сказал: «Семена взошли».", "— Семена взошли весной.", "«Мышкин», — сказал он.", "Позвали Семена. «Семена взошли»."))
        println("${vis(t)} → ${vis(RussianNames.restore(null, t))}")
    println("--- голосование: слово рядом с кавычкой / апострофом")
    fun plan(llm: String, sil: String) = StressCheck.plan(listOf(llm), listOf(sil), { null }, { null }).let { "disputes=${it.disputes.size} single=${it.single} → ${StressCheck.resolve(it, null).single()}" }
    println("Q20 д’Артаньян: " + plan("Пришёл д’Артанья́н.", "Пришёл д’Арта́ньян."))
    println("Q21 Silero без кавычек (несовпадение выравнивания): " + plan("Он сказа́л «Ура́».", "Он сказа́л Ура́."))
    println("Q22 мягкий перенос: " + plan("Он пил мо­локо́.", "Он пил мо­ло́ко."))
}

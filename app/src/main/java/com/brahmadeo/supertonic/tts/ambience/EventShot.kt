package com.brahmadeo.supertonic.tts.ambience

/** Может ли звук события прозвучать прямо сейчас. Событие — это то, ради чего слушатель «там»: дверь хлопнула,
 * заскрипели половицы, завёлся мотор. Оно не принадлежит фону локации и обязано звучать даже там, где фона нет
 * (улица, двор, между сценами), и во время затухания фона. Раньше звук терялся именно в таких местах.
 * Глушим только когда речь не идёт вовсе — то есть чтение стоит. */
object EventShot {
    fun allowed(speech: Boolean, bedPlaying: Boolean, bedMaster: Float): Boolean =
        speech || (bedPlaying && bedMaster > 0f)
}

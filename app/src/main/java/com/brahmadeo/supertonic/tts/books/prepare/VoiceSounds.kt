package com.brahmadeo.supertonic.tts.books.prepare

/**
 * Слышимые голосовые звуки, которые облачная разметка иногда пропускает: плач, крик, смех, шёпот, вздох. Слово в тексте
 * названо прямо, поэтому второй запрос к модели не нужен — звук ставится по глаголу, локально и бесплатно.
 *
 * Правило намеренно узкое: только глаголы в тех формах, что перечислены. Отрицание («не заплакал») пропускается:
 * тишина в таком месте правильнее любого звука.
 */
object VoiceSounds {

    /** Формы слова (в нижнем регистре, без знаков по краям) → вид события приложения. */
    private val FORMS: Map<String, List<String>> = mapOf(
        "cry" to listOf(
            "заплакал", "заплакала", "заплакали", "разревелся", "разревелась", "расплакался", "расплакалась",
            "всхлипнул", "всхлипнула", "всхлипывает", "зарыдал", "зарыдала", "рыдает", "рыдал", "рыдала",
            "плачет", "плакал", "плакала", "плачут"
        ),
        "shout" to listOf(
            "закричал", "закричала", "закричали", "крикнул", "крикнула", "вскрикнул", "вскрикнула",
            "заорал", "заорала", "кричит", "завопил", "завопила"
        ),
        "laugh_soft" to listOf(
            "засмеялся", "засмеялась", "рассмеялся", "рассмеялась", "рассмеялись", "хихикнул", "хихикнула",
            "смеётся", "смеется", "захохотал", "захохотала"
        ),
        "whisper" to listOf("прошептал", "прошептала", "шепнул", "шепнула", "шепчет", "шепчут"),
        "sigh" to listOf("вздохнул", "вздохнула", "вздыхает", "вздохнули")
    )

    /** Виды, которые это правило умеет ставить (все есть в списке приложения). */
    val kinds: List<String> get() = FORMS.keys.toList()

    /** Слово без знаков по краям, в нижнем регистре: «Заплакал,» → «заплакал». */
    fun clean(word: String): String = word.lowercase().trim('.', ',', '!', '?', '…', '—', '–', '«', '»', '"', '\'', '(', ')', ';', ':')

    /** Номер слова, где назван звук [kind], или null. Формы сравниваются по началу слова: «заплакал» и «заплакала». */
    fun index(words: List<String>, kind: String): Int? {
        val forms = FORMS[kind] ?: return null
        for ((i, w) in words.withIndex()) {
            val c = clean(w)
            if (c.isEmpty()) continue
            if (forms.any { f -> c == f || (c.length > f.length && c.startsWith(f)) }) {
                if (!negated(words, i)) return i
            }
        }
        return null
    }

    /** «не заплакал», «ни разу не плакал»: перед глаголом в пределах двух слов стоит отрицание. */
    fun negated(words: List<String>, at: Int): Boolean {
        for (k in maxOf(0, at - 2) until at) {
            val c = clean(words[k])
            if (c == "не" || c == "ни" || c == "никогда" || c == "больше") return true
        }
        return false
    }
}

package com.brahmadeo.supertonic.tts

import android.os.Bundle
import android.util.Log
import androidx.activity.ComponentActivity
import androidx.activity.compose.rememberLauncherForActivityResult
import androidx.activity.compose.setContent
import androidx.activity.enableEdgeToEdge
import androidx.activity.result.contract.ActivityResultContracts
import androidx.compose.foundation.layout.*
import androidx.compose.foundation.rememberScrollState
import androidx.compose.foundation.verticalScroll
import androidx.compose.material3.*
import androidx.compose.runtime.*
import androidx.compose.ui.Modifier
import androidx.compose.ui.unit.dp
import com.brahmadeo.supertonic.tts.ambience.AmbienceModel
import com.brahmadeo.supertonic.tts.ambience.AmbienceSettings
import com.brahmadeo.supertonic.tts.ambience.AmbienceSettings.musicOn
import com.brahmadeo.supertonic.tts.music.BackgroundMusic
import com.brahmadeo.supertonic.tts.music.GeneratedMusic
import androidx.compose.foundation.gestures.detectTapGestures
import androidx.compose.ui.input.pointer.pointerInput
import com.brahmadeo.supertonic.tts.music.MusicFiles
import com.brahmadeo.supertonic.tts.music.MusicCatalog
import com.brahmadeo.supertonic.tts.ui.theme.SupertonicTheme
import kotlinx.coroutines.launch
import kotlin.math.roundToInt

class BackgroundMusicActivity : ComponentActivity() {
    override fun onCreate(savedInstanceState: Bundle?) {
        super.onCreate(savedInstanceState)
        enableEdgeToEdge()
        BackgroundMusic.initialize(this)
        setContent {
            SupertonicTheme {
                val prefs=remember { getSharedPreferences("SupertonicPrefs",MODE_PRIVATE) }
                val catalog=remember { MusicCatalog.tracks(this) }
                var installed by remember { mutableStateOf(catalog.filter { MusicCatalog.ready(this,it)!=null }.map { it.id }.toSet()) }
                var enabled by remember { mutableStateOf(prefs.getBoolean("background_music_enabled",false)) }
                var selected by remember { mutableStateOf(MusicCatalog.ensureDefault(this)) }
                var customName by remember { mutableStateOf(if(MusicFiles.custom(this)!=null) prefs.getString("background_music_name","Свой MP3").orEmpty() else "") }
                var volume by remember { mutableIntStateOf(prefs.getInt("background_music_volume",BackgroundMusic.DEFAULT_VOLUME).coerceIn(0,100)) }
                var ambience by remember { mutableStateOf(AmbienceSettings.enabled(prefs)) }
                var ambienceVolume by remember { mutableIntStateOf(AmbienceSettings.volume(prefs)) }
                var ambienceReady by remember { mutableStateOf(AmbienceModel.ready(this)) }
                var ambienceNpu by remember { mutableStateOf(prefs.getBoolean(AmbienceModel.NPU_KEY,false)) }
                var npuNight by remember { mutableStateOf(AmbienceSettings.npuNight(prefs)) }
                var ambienceTame by remember { mutableStateOf(AmbienceSettings.tame(prefs)) }
                var breathe by remember { mutableStateOf(AmbienceSettings.breathe(prefs)) }
                var events by remember { mutableStateOf(AmbienceSettings.events(prefs)) }
                var eventsVolume by remember { mutableIntStateOf(AmbienceSettings.eventsVolume(prefs)) }
                var eventsDensity by remember { mutableIntStateOf(prefs.getInt(com.brahmadeo.supertonic.tts.books.prepare.SceneMarking.EVENTS_DENSITY,
                    com.brahmadeo.supertonic.tts.books.prepare.SceneMarking.DEFAULT_DENSITY)) }
                var moodMusic by remember { mutableStateOf(AmbienceSettings.moodMusic(prefs)) }
                var moodByChapter by remember { mutableStateOf(AmbienceSettings.moodByChapter(prefs)) }
                var room by remember { mutableStateOf(prefs.getBoolean(com.brahmadeo.supertonic.tts.ambience.VoiceRoom.KEY,false)) }
                var roomStrength by remember { mutableIntStateOf(prefs.getInt(com.brahmadeo.supertonic.tts.ambience.VoiceRoom.STRENGTH,100).coerceIn(0,200)) }
                var chapters by remember { mutableStateOf(AmbienceSettings.chapters(prefs)) }
                var ambienceVariants by remember { mutableIntStateOf(AmbienceSettings.variants(prefs)) }
                var busy by remember { mutableStateOf(false) }
                var generated by remember { mutableStateOf(GeneratedMusic.list(this)) }
                var musicText by remember { mutableStateOf("") }
                var musicSeconds by remember { mutableIntStateOf(60) }
                var enhance by remember { mutableStateOf(com.brahmadeo.supertonic.tts.ambience.MusicEnhance.enabled(this)) }
                var musicModel by remember { mutableStateOf(AmbienceModel.music(this).id) }
                var largeDecoder by remember { mutableStateOf(AmbienceModel.largeDecoderWanted(this)) }
                val creating by com.brahmadeo.supertonic.tts.ambience.AmbienceGeneration.state.collectAsState()
                LaunchedEffect(creating.running) { if (!creating.running) generated = GeneratedMusic.list(this@BackgroundMusicActivity) }
                /** Long press on a track: «Удалить?» (title, action). */
                var toDelete by remember { mutableStateOf<Pair<String, () -> Unit>?>(null) }
                var message by remember { mutableStateOf("") }
                val error by BackgroundMusic.status.collectAsState()
                val scope=rememberCoroutineScope()
                /** «▶» a made track: plays it once in this screen (stopped by «■», another track, or leaving). */
                var previewId by remember { mutableStateOf<String?>(null) }
                val preview = remember { arrayOfNulls<android.media.MediaPlayer>(1) }
                fun stopPreview() { preview[0]?.let { runCatching { it.stop() }; it.release() }; preview[0] = null; previewId = null }
                fun playPreview(t: GeneratedMusic.Track) {
                    stopPreview()
                    preview[0] = runCatching { android.media.MediaPlayer().apply {
                        setAudioAttributes(android.media.AudioAttributes.Builder().setUsage(android.media.AudioAttributes.USAGE_MEDIA)
                            .setContentType(android.media.AudioAttributes.CONTENT_TYPE_MUSIC).build())
                        setDataSource(t.file.path); setOnCompletionListener { stopPreview() }; prepare(); start()
                    } }.onFailure { message = "Не удалось воспроизвести трек" }.getOrNull()
                    if (preview[0] != null) previewId = t.id
                }
                DisposableEffect(Unit) {
                    val stopOnLeave = androidx.lifecycle.LifecycleEventObserver { _, e -> if (e == androidx.lifecycle.Lifecycle.Event.ON_STOP) stopPreview() }
                    lifecycle.addObserver(stopOnLeave)
                    onDispose { lifecycle.removeObserver(stopOnLeave); stopPreview() }
                }
                /** «Скачать» a made track: copied as .m4a to where the user picks (Downloads, Music…). */
                var toSave by remember { mutableStateOf<GeneratedMusic.Track?>(null) }
                val saver=rememberLauncherForActivityResult(ActivityResultContracts.CreateDocument("audio/mp4")) { uri ->
                    val track=toSave; toSave=null
                    if(uri!=null && track!=null) scope.launch {
                        message=try {
                            kotlinx.coroutines.withContext(kotlinx.coroutines.Dispatchers.IO) {
                                contentResolver.openOutputStream(uri,"w")?.use { out -> track.file.inputStream().use { it.copyTo(out) } } ?: error("не удалось записать")
                            }
                            "Трек «${track.title}» сохранён"
                        } catch(t: Exception) { "Не удалось сохранить трек: ${t.message.orEmpty()}" }
                    }
                }
                val picker=rememberLauncherForActivityResult(ActivityResultContracts.OpenDocument()) { uri ->
                    if(uri!=null) {
                        busy=true; message="Загрузка MP3…"
                        scope.launch {
                            try {
                                customName=MusicFiles.import(this@BackgroundMusicActivity,uri)
                                selected="custom"; enabled=true; message="MP3 добавлен"
                            } catch(t: Exception) { message="Не удалось загрузить MP3: ${t.message.orEmpty()}" }
                            finally { busy=false }
                        }
                    }
                }
                fun select(track: String) {
                    selected=track; enabled=true
                    prefs.edit().putString("background_music_track",track).musicOn().apply()
                }
                toDelete?.let { (title, action) ->
                    AlertDialog(onDismissRequest = { toDelete = null }, title = { Text("Удалить трек?") }, text = { Text("«$title» будет удалён с телефона.") },
                        confirmButton = { TextButton(onClick = { toDelete = null; action() }) { Text("Удалить") } },
                        dismissButton = { TextButton(onClick = { toDelete = null }) { Text("Отмена") } })
                }
                Surface(Modifier.fillMaxSize()) {
                    Column(Modifier.fillMaxSize().safeDrawingPadding().verticalScroll(rememberScrollState()).padding(20.dp),
                        verticalArrangement=Arrangement.spacedBy(14.dp)) {
                        Text("Фоновая музыка",style=MaterialTheme.typography.headlineMedium)
                        Text("Выбранный трек играет по кругу во время чтения. Пауза останавливает речь и музыку; продолжение сохраняет место в треке.")
                        Row(Modifier.fillMaxWidth(),horizontalArrangement=Arrangement.SpaceBetween) {
                            Text("Включить музыку",Modifier.weight(1f))
                            Switch(checked=enabled && selected.isNotEmpty(),enabled=!busy && selected.isNotEmpty(),onCheckedChange={
                                enabled=it
                                if(it) prefs.edit().musicOn().apply() else prefs.edit().putBoolean("background_music_enabled",false).apply()
                            })
                        }
                        Text("Громкость фона: $volume %",style=MaterialTheme.typography.titleMedium)
                        Slider(value=volume.toFloat(),onValueChange={ volume=it.roundToInt(); BackgroundMusic.volumePreview(volume) },
                            onValueChangeFinished={ prefs.edit().putInt("background_music_volume",volume).apply() },
                            valueRange=0f..100f,steps=99)
                        Text("0 % — беззвучно. По умолчанию 10 %. Громкость речи не изменяется.",style=MaterialTheme.typography.bodySmall)
                        HorizontalDivider()
                        Text("Готовые треки",style=MaterialTheme.typography.titleLarge)
                        Button(enabled=!busy && installed.size<catalog.size,onClick={
                            busy=true
                            scope.launch {
                                try {
                                    MusicCatalog.download(this@BackgroundMusicActivity) { percent,title ->
                                        runOnUiThread { message="$title — $percent %" }
                                    }
                                    message="Музыка загружена. Выберите трек ниже."
                                } catch(t: Exception) { message="Не удалось скачать: ${t.message.orEmpty()}" }
                                finally {
                                    installed=catalog.filter { MusicCatalog.ready(this@BackgroundMusicActivity,it)!=null }.map { it.id }.toSet()
                                    selected=MusicCatalog.ensureDefault(this@BackgroundMusicActivity)
                                    busy=false
                                }
                            }
                        }) { Text(when { installed.size==catalog.size -> "Музыка скачана"; installed.isEmpty() -> "Скачать музыку"; else -> "Скачать новые композиции" }) }
                        Text("${catalog.size} ${compositions(catalog.size)}, около ${(catalog.sumOf { it.size } + 524288) / 1048576} МБ. После скачивания интернет не нужен.",style=MaterialTheme.typography.bodySmall)
                        Text("Долгое нажатие на трек — удалить его с телефона.",style=MaterialTheme.typography.bodySmall)
                        for(track in catalog) {
                            val available=track.id in installed
                            Row(Modifier.fillMaxWidth().pointerInput(track.id,available,busy) { detectTapGestures(
                                onTap = { if (!busy && available) select("ready:${track.id}") },
                                onLongPress = { if (!busy && available) toDelete = track.title to {
                                busy=true
                                scope.launch {
                                    try {
                                        MusicCatalog.remove(this@BackgroundMusicActivity,track)
                                        installed=installed-track.id
                                        selected=prefs.getString("background_music_track","").orEmpty()
                                        enabled=prefs.getBoolean("background_music_enabled",false)
                                        message="Композиция удалена с телефона"
                                    } catch(t: Exception) { message="Не удалось удалить: ${t.message.orEmpty()}" }
                                    finally { busy=false }
                                }
                                Unit } }) },horizontalArrangement=Arrangement.SpaceBetween) {
                                Text(track.title+if(available) "" else " (не скачано)",Modifier.weight(1f).padding(top=12.dp))
                                RadioButton(selected=selected=="ready:${track.id}",enabled=!busy && available,onClick={select("ready:${track.id}")})
                            }
                        }
                        HorizontalDivider()
                        Text("Свой трек",style=MaterialTheme.typography.titleLarge)
                        if(customName.isNotEmpty()) {
                            Row(Modifier.fillMaxWidth().pointerInput(customName,busy) { detectTapGestures(
                                onTap = { if (!busy) select("custom") },
                                onLongPress = { if (!busy) toDelete = customName to {
                                    busy=true
                                    scope.launch {
                                        try {
                                            MusicFiles.remove(this@BackgroundMusicActivity)
                                            customName=""
                                            if(selected=="custom") { selected=""; enabled=false }
                                            message="Свой MP3 удалён"
                                        } catch(t: Exception) { message="Не удалось удалить: ${t.message.orEmpty()}" }
                                        finally { busy=false }
                                    }
                                    Unit } }) },horizontalArrangement=Arrangement.SpaceBetween) {
                                Text(customName,Modifier.weight(1f).padding(top=12.dp))
                                RadioButton(selected=selected=="custom",enabled=!busy,onClick={select("custom")})
                            }
                        }
                        Button(enabled=!busy,onClick={picker.launch(arrayOf("audio/mpeg","audio/mp3"))}) {
                            Text(if(customName.isEmpty()) "Загрузить свой MP3" else "Заменить свой MP3")
                        }
                        HorizontalDivider()
                        Text("Своя музыка",style=MaterialTheme.typography.titleLarge)
                        Text("Музыка по вашему описанию, создаётся на телефоне — без подготовки книги. Модель понимает только английский: " +
                            "описание на русском переводится автоматически (облако, а без него — Gemma 4); для точности можно сразу писать " +
                            "по-английски. Готовый трек зацикливается без стыка и появляется в списке ниже; «Скачать» сохраняет его файлом .m4a на телефон.",style=MaterialTheme.typography.bodySmall)
                        Text("Модель хуже всего справляется со струнными (скрипка, виолончель): в высоких нотах возможны артефакты и " +
                            "«пластмассовый» звук. Лучше получаются фортепиано, гитара, духовые, эмбиент и шумовые подложки.",
                            style=MaterialTheme.typography.bodySmall,color=MaterialTheme.colorScheme.error)
                        for (g in generated) {
                            Row(Modifier.fillMaxWidth().pointerInput(g.id,busy) { detectTapGestures(
                                onTap = { if (!busy) select("gen:${g.id}") },
                                onLongPress = { if (!busy) toDelete = g.title to {
                                    if (previewId==g.id) stopPreview()
                                    GeneratedMusic.remove(this@BackgroundMusicActivity, g.id)
                                    generated = GeneratedMusic.list(this@BackgroundMusicActivity)
                                    if (selected == "gen:${g.id}") { selected = ""; enabled = false }
                                    message = "Трек удалён"
                                    Unit } }) },horizontalArrangement=Arrangement.SpaceBetween) {
                                Text("${g.title} · ${g.seconds} с",Modifier.weight(1f).padding(top=12.dp))
                                TextButton(onClick={ if (previewId==g.id) stopPreview() else playPreview(g) }) {
                                    Text(if (previewId==g.id) "■ Стоп" else "▶ Слушать") }
                                TextButton(enabled=!busy,onClick={
                                    toSave=g; saver.launch(g.title.replace(Regex("[\\\\/:*?\"<>|]"),"_").ifBlank { "Музыка" } + ".m4a") }) { Text("Скачать") }
                                RadioButton(selected=selected=="gen:${g.id}",enabled=!busy,onClick={select("gen:${g.id}")})
                            }
                        }
                        Text("Модель музыки",style=MaterialTheme.typography.titleMedium)
                        for (m in listOf(AmbienceModel.SMALL_MUSIC, AmbienceModel.MEDIUM_MUSIC)) {
                            Row(Modifier.fillMaxWidth(),verticalAlignment=androidx.compose.ui.Alignment.CenterVertically) {
                                RadioButton(selected=musicModel==m.id,enabled=!creating.running,onClick={
                                    musicModel=m.id; prefs.edit().putString(AmbienceModel.MUSIC_MODEL_KEY,m.id).apply() })
                                Text("${m.title} · ${m.assets.sumOf { it.size }/1048576} МБ")
                            }
                        }
                        Text("Средняя (1,4 млрд параметров) звучит чище и естественнее, но создаёт музыку примерно в 2,5 раза дольше " +
                            "и требует до ~3,5 ГБ памяти при создании. Действует на новые треки и музыку по настроению; скачивается при первом создании.",
                            style=MaterialTheme.typography.bodySmall)
                        Row(Modifier.fillMaxWidth(),horizontalArrangement=Arrangement.SpaceBetween) {
                            Text("Большой декодер звука",Modifier.weight(1f))
                            Switch(checked=largeDecoder,enabled=!creating.running,onCheckedChange={ largeDecoder=it; prefs.edit().putBoolean(AmbienceModel.LARGE_DECODER_KEY,it).apply() })
                        }
                        Text("Точнее восстанавливает звук (немного больше верхов и деталей), +${AmbienceModel.LARGE_DECODER.sumOf { it.size }/1048576} МБ " +
                            "и примерно на треть дольше. Работает с обеими моделями.",style=MaterialTheme.typography.bodySmall)
                        Row(Modifier.fillMaxWidth(),horizontalArrangement=Arrangement.SpaceBetween) {
                            Text("Улучшать звук музыки",Modifier.weight(1f))
                            Switch(checked=enhance,onCheckedChange={ enhance=it; prefs.edit().putBoolean(com.brahmadeo.supertonic.tts.ambience.MusicEnhance.KEY,it).apply() })
                        }
                        Text("Модель музыки звучит глуховато («как через трубу»). Фильтр при создании достраивает верхние гармоники, " +
                            "чуть поднимает верха и расширяет стерео. Действует на новые треки и музыку по настроению.",style=MaterialTheme.typography.bodySmall)
                        OutlinedTextField(value=musicText,onValueChange={ musicText=it.take(300) },modifier=Modifier.fillMaxWidth(),
                            label={ Text("Описание музыки") },placeholder={ Text("Например: спокойное пианино и виолончель, дождливый вечер") },
                            enabled=!creating.running,minLines=2)
                        Row(Modifier.fillMaxWidth(),verticalAlignment=androidx.compose.ui.Alignment.CenterVertically) {
                            for (sec in listOf(30, 60, 120)) {
                                RadioButton(selected=musicSeconds==sec,enabled=!creating.running,onClick={ musicSeconds=sec })
                                Text("$sec с",Modifier.padding(end=12.dp))
                            }
                        }
                        Text("30 с — быстрее всего (на NPU, если он включён), 60 и 120 с — на процессоре, до минуты. " +
                            "Первый раз скачивается выбранная модель музыки (${AmbienceModel.musicBytes(this@BackgroundMusicActivity)/1048576} МБ, с NPU — ещё графы для него).",style=MaterialTheme.typography.bodySmall)
                        if (creating.running && creating.book == null) {
                            Text(creating.place.ifEmpty { "Создание музыки" })
                            LinearProgressIndicator(Modifier.fillMaxWidth())
                            OutlinedButton(onClick=com.brahmadeo.supertonic.tts.ambience.AmbienceGeneration::stop) { Text("Остановить") }
                        } else Button(enabled=!busy && !creating.running && musicText.isNotBlank(),onClick={
                            com.brahmadeo.supertonic.tts.ambience.AmbienceGeneration.startMusic(this@BackgroundMusicActivity, musicText, musicSeconds)
                        }) { Text("Создать музыку") }
                        if (!creating.running && creating.book == null && creating.message.isNotBlank()) Text(creating.message)
                        Text("Файл сохраняется в приложении и доступен без интернета.",style=MaterialTheme.typography.bodySmall)
                        HorizontalDivider()
                        Text("Фоновые звуки локаций · эксперимент",style=MaterialTheme.typography.titleLarge)
                        Text("Для книг, подготовленных в MyTTS с локациями: звук места действия по ходу чтения — поезд, кафе, улица, лес. " +
                            "Звуки создаются на телефоне один раз для каждой локации книги и хранятся в её файле. В сценах с локацией играет её звук, " +
                            "а там, где сцены нет (рассуждения автора, нераспознанные места), — фоновая музыка, если она включена. " +
                            "Одновременно они не звучат, переход плавный.",style=MaterialTheme.typography.bodySmall)
                        Row(Modifier.fillMaxWidth(),horizontalArrangement=Arrangement.SpaceBetween) {
                            Text("Включить фоновые звуки",Modifier.weight(1f))
                            Switch(checked=ambience,enabled=!busy,onCheckedChange={
                                ambience=it; AmbienceSettings.setAmbience(prefs,it)
                            })
                        }
                        Text("Громкость звуков: $ambienceVolume %",style=MaterialTheme.typography.titleMedium)
                        Slider(value=ambienceVolume.toFloat(),onValueChange={ ambienceVolume=it.roundToInt() },
                            onValueChangeFinished={ prefs.edit().putInt(AmbienceSettings.VOLUME,ambienceVolume).apply() },
                            valueRange=0f..100f,steps=99)
                        Text("По умолчанию 30 %. Громкость речи не изменяется.",style=MaterialTheme.typography.bodySmall)
                        Row(Modifier.fillMaxWidth(),horizontalArrangement=Arrangement.SpaceBetween) {
                            Text("Сглаживать резкие звуки",Modifier.weight(1f))
                            Switch(checked=ambienceTame,enabled=!busy,onCheckedChange={ ambienceTame=it; prefs.edit().putBoolean(AmbienceSettings.TAME,it).apply() })
                        }
                        Text("Гудки, смех, удары и другие акценты внутри звука локации не громче ровного фона больше чем на ~3 дБ и не " +
                            "перебивают голос. Звуки событий не сглаживаются — у них своя громкость. Действует сразу, звуки пересоздавать не нужно.",
                            style=MaterialTheme.typography.bodySmall)
                        Row(Modifier.fillMaxWidth(),horizontalArrangement=Arrangement.SpaceBetween) {
                            Text("Звуки событий",Modifier.weight(1f))
                            Switch(checked=events,enabled=!busy,onCheckedChange={ events=it; prefs.edit().putBoolean(AmbienceSettings.EVENTS,it).apply() })
                        }
                        Text("Короткие звуки того, что происходит в тексте: хлопнула дверь, шаги, шелест бумаг, выстрел — в момент, " +
                            "когда голос до этого доходит. Один звук создаётся на вид действия (дверь, бумаги, вода, посуда) и звучит " +
                            "во всех местах книги, поэтому моментов много, а клипов немного. Нужна книга, подготовленная в этой " +
                            "версии или новее.", style=MaterialTheme.typography.bodySmall)
                        if (events) {
                            Text("Громкость звуков событий: $eventsVolume %",style=MaterialTheme.typography.titleMedium)
                            Slider(value=eventsVolume.toFloat(),onValueChange={ eventsVolume=it.roundToInt() },
                                onValueChangeFinished={ prefs.edit().putInt(AmbienceSettings.EVENTS_VOLUME,eventsVolume).apply() },
                                valueRange=0f..100f,steps=99)
                            Text("Отдельно от звуков локаций; по умолчанию 40 % — чуть выше фона. Действует сразу.",style=MaterialTheme.typography.bodySmall)
                            Text("Сколько событий отмечать",style=MaterialTheme.typography.titleMedium)
                            for ((d, label) in listOf(1 to "Редко: только прямо описанные звуки (выстрел, гром, хлопнула дверь)",
                                    2 to "Обычно: звуки и заметные действия героев (шаги, дверь, посуда, бумаги)",
                                    3 to "Часто: всё слышимое, в том числе то, о чём говорят (бумаги, деньги, дверь)")) {
                                Row(Modifier.fillMaxWidth(),verticalAlignment=androidx.compose.ui.Alignment.CenterVertically) {
                                    RadioButton(selected=eventsDensity==d,enabled=!busy,onClick={ eventsDensity=d
                                        prefs.edit().putInt(com.brahmadeo.supertonic.tts.books.prepare.SceneMarking.EVENTS_DENSITY,d).apply() })
                                    Text(label,Modifier.weight(1f))
                                }
                            }
                            Text("Действует при подготовке книги (нужно подготовить её заново). Событие отмечается по словам цитаты " +

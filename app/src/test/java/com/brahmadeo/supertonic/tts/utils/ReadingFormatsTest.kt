package com.brahmadeo.supertonic.tts.utils

import com.brahmadeo.supertonic.tts.foreign.ForeignText
import org.junit.Assert.assertEquals
import org.junit.Assert.assertTrue
import org.junit.Test

/** Every format is read the same way with and without the LLM: the LLM input is the book normalizer without dates,
 * then prepareNumbers (dates and plain integers with spans); the offline path is the full book normalizer. */
class ReadingFormatsTest {
    private val numbers = RussianNumberNormalizer()
    private fun llm(text: String) = ForeignText.prepareNumbers(RussianBookNormalizer.normalize(text, expandNumbers = false, dates = false), numbers).text
    private fun offline(text: String) = RussianBookNormalizer.normalize(text)
    private fun both(expected: String, source: String) {
        assertEquals(expected, llm(source))
        assertEquals(expected, offline(source))
    }

    @Test fun romanNumerals() {
        both("Пётр Первый основал Петербург в восемнадцатом веке; глава вторая называлась «Начало».",
            "Пётр I основал Петербург в XVIII веке; глава II называлась «Начало».")
        both("Екатерина Вторая и Николай Второй правили долго; при Петре Первом построили флот, а Людовик Четырнадцатый жил во Франции.",
            "Екатерина II и Николай II правили долго; при Петре I построили флот, а Людовик XIV жил во Франции.")
        both("Глава первая.", "I.")
        both("Глава третья. Том второй. В двадцатом веке и к двадцать первому веку.", "Глава III. Том II. В XX веке и к XXI веку.")
        both("В девятнадцатом и двадцатом веках жили по-разному.", "В XIX и XX веках жили по-разному.")
        assertTrue(ForeignText.split(RussianBookNormalizer.normalize("Пётр I и Екатерина II", expandNumbers = false)).none { it.foreign })
    }

    @Test fun datesAndYears() {
        both("В тысяча девятьсот сорок первом — тысяча девятьсот сорок пятом годах шла война, а с тысяча девятьсот сорок первого по тысяча девятьсот сорок пятый год погибли миллионы.",
            "В 1941–1945 гг. шла война, а с 1941 по 1945 год погибли миллионы.")
        both("Он писал двадцатого августа тысяча девятьсот девяносто первого года, что к двухтысячному всё изменится; в тысяча девятьсот девяностые годы и в девяностых жизнь была трудной.",
            "Он писал 20.08.91, что к 2000 всё изменится; в 1990-е годы и в 90-х жизнь была трудной.")
        both("Август тысяча девятьсот девяносто первого запомнили все; двадцатого августа он вернулся.", "Август 1991-го запомнили все; 20-го августа он вернулся.")
        both("В тысяча девятьсот девяносто первом он уехал.", "В 1991 он уехал.")
        both("Война тысяча девятьсот сорок первого — тысяча девятьсот сорок пятого изменила всё.", "Война 1941–1945 изменила всё.")
    }

    @Test fun unitsTimesPercentsPhones() {
        both("Расстояние пять километров, вес два килограмма, стоимость триста рублей.", "Расстояние 5 км, вес 2 кг, стоимость 300 руб.")
        both("Встреча назначена на десять часов тридцать минут.", "Встреча назначена на 10:30.")
        both("Цены выросли на пятнадцать процентов, температура упала до минус пяти градусов Цельсия.", "Цены выросли на 15%, температура упала до -5°C.")
        both("Телефон плюс семь девятьсот двенадцать триста сорок пять шестьдесят семь восемьдесят девять.", "Телефон +7 912 345-67-89.")
        both("Было от десяти до пятнадцати человек, от пяти до десяти километров пути.", "Было 10-15 человек, 5-10 км пути.")
        both("Купил за триста рублей. Потом ушёл.", "Купил за 300 руб. Потом ушёл.")
        both("В девяностых годах он жил на третьем этаже.", "В 90-х годах он жил на 3-м этаже.")
    }

    @Test fun countedNounsAgree() {
        both("У него была двадцать одна книга и две тетради; он прочитал сто одну страницу за три дня.",
            "У него была 21 книга и 2 тетради; он прочитал 101 страницу за 3 дня.")
        assertEquals("два имени и одно время", llm("2 имени и 1 время"))
        assertEquals("два стола и два окна, одна ночь и один день", llm("2 стола и 2 окна, 1 ночь и 1 день"))
    }

    @Test fun abbreviations() {
        both("эс-эс-эс-эр, эс-ша-а, эф-эс-бэ, ка-гэ-бэ, эм-гэ-у, вэ-вэ-пэ и эн-ка-вэ-дэ, а также нато, оон, мид, гулаг и е-гэ-э.",
            "СССР, США, ФСБ, КГБ, МГУ, ВВП и НКВД, а также НАТО, ООН, МИД, ГУЛАГ и ЕГЭ.")
        both("Он крикнул: кто там? всё! да!", "Он крикнул: КТО ТАМ? ВСЁ! ДА!")
    }
}

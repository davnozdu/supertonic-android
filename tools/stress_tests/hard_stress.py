if sys.argv[1] == "write":
    open(sys.argv[2], "w", encoding="utf-8").write("\n\n".join(c[0] for c in CASES) + "\n")
else:
    out = json.load(open(sys.argv[2], encoding="utf-8"))
    field = sys.argv[3] if len(sys.argv) > 3 else "text"
    by_source = {r["source"]: (r["text"] if field == "text" else (r.get(field) or r["source"])) for r in out}
    ok = total = 0
    for src, expected in CASES:
        text = by_source.get(src, "")
        words = [w.strip(".,:;?!") for w in text.split()]
        used = set()
        for e in expected:
            want = s(e); bare = want.replace(A, "").lower()
            idx = next((i for i, w in enumerate(words) if i not in used and w.replace(A, "").lower() == bare), None)
            total += 1
            got = words[idx] if idx is not None else "?"
            if idx is not None: used.add(idx)
            if got.lower() == want.lower(): ok += 1
            else: print(f"  MISS want {want:16} got {got}")
    print(f"correct {ok}/{total}")
